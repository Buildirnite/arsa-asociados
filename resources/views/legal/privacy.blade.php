            <h2>2. Datos que recopilamos</h2>
            <p>A través del formulario de contacto recopilamos:</p>
            <ul>
                <li>Nombre completo</li>
                <li>Correo electrónico</li>
                <li>Número de teléfono (opcional)</li>
                <li>Descripción de su consulta legal</li>
            </ul>

            <h2>3. Finalidad del tratamiento</h2>
            <p>Los datos recopilados se utilizan exclusivamente para:</p>
            <ul>
                <li>Responder a su consulta legal</li>
                <li>Coordinar una primera entrevista o asesoría</li>
                <li>Mantener comunicación relacionada con servicios legales solicitados</li>
            </ul>
            <p>No utilizamos sus datos para envío de publicidad no solicitada ni los compartimos con terceros.</p>

            <h2>4. Base legal</h2>
            <p>
                El tratamiento de sus datos se realiza en virtud del consentimiento otorgado al completar
                el formulario de contacto, conforme a la Ley N.° 19.628 sobre Protección de la Vida Privada
                de la República de Chile.
            </p>

            <h2>5. Conservación de datos</h2>
            <p>
                Sus datos serán conservados durante el tiempo necesario para atender su consulta y,
                en caso de establecerse una relación profesional, durante el período que exija la normativa
                aplicable al ejercicio de la abogacía.
            </p>

            <h2>6. Derechos del titular</h2>
            <p>Usted tiene derecho a:</p>
            <ul>
                <li>Acceder a sus datos personales</li>
                <li>Solicitar la rectificación de datos inexactos</li>
                <li>Solicitar la eliminación de sus datos</li>
                <li>Oponerse al tratamiento de sus datos</li>
            </ul>
            <p>
                Para ejercer estos derechos, escríbanos a
                <a href="mailto:contacto@arsayasociados.cl">contacto@arsayasociados.cl</a>.
            </p>

            <h2>7. Seguridad</h2>
            <p>
                Adoptamos medidas técnicas y organizativas razonables para proteger sus datos personales
                frente a acceso no autorizado, pérdida o divulgación indebida.
            </p>

            <h2>8. Cambios a esta política</h2>
            <p>
                Nos reservamos el derecho de actualizar esta política. Cualquier cambio relevante
